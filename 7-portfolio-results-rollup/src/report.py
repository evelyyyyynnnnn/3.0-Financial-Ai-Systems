"""Render results/README.md from the same run that wrote results/latest.json.

Ground rule 1 of the portfolio is that no number may be cited unless it appears
in a results README with a run date behind it. That makes this file the one a
reviewer reads, which makes a hand-maintained copy the worst possible design:
it goes stale silently, and a stale evidence file is worse than none. So it is
generated from the run, exactly like the website is.
"""

from __future__ import annotations


def _fmt(v) -> str:
    if isinstance(v, float):
        return f"{v:.4g}"
    if isinstance(v, int):
        return f"{v:,}"
    return str(v)


def render(results: dict) -> str:
    s = results["summary"]
    rows = results["projects"]
    real = [p for p in rows if p.get("is_synthetic") is False]
    synth = [p for p in rows if p.get("is_synthetic") is True]

    out: list = []
    add = out.append

    add("# Results — Portfolio Roll-up")
    add("")
    add("> Generated by `python -m src.demo`. Do not edit by hand: every figure")
    add("> below is read from the file that project's own demo wrote, and this")
    add("> page is rewritten from the same run that writes `latest.json`.")
    add("")
    add(f"**Run date:** `{results['generated_at']}`")
    add("")

    add("## Portfolio at a glance")
    add("")
    add("| | Count |")
    add("|---|---|")
    add(f"| Projects walked | {s['n_projects']} |")
    add(f"| With a recorded run | {s['n_with_results']} |")
    add(f"| Never run | {s['n_never_run']} |")
    add(f"| Running on **real** data | {s['n_real_data']} |")
    add(f"| Running on synthetic or authored data | {s['n_synthetic_data']} |")
    add(f"| With a published website | {s['n_with_site']} |")
    add(f"| Test functions across the portfolio | {s['total_tests']} |")
    add("")
    add(f"Repositories walked: {', '.join('`' + r + '`' for r in s['repos'])}.")
    add("")

    add("## Every project, and what it ran on")
    add("")
    add("| Repository | Project | Run date | Data | Tests | Site |")
    add("|---|---|---|---|---:|---|")
    for p in rows:
        if not p["has_results"]:
            data = "**never run**"
        elif p.get("is_synthetic") is False:
            data = "real"
        else:
            data = "synthetic / authored"
        date = (p.get("generated_at") or "")[:10] or "—"
        site = "yes" if p.get("has_site") else "no"
        add(f"| `{p['repo']}` | `{p['project']}` | {date} | {data} | "
            f"{p['n_tests']} | {site} |")
    add("")

    add("### Data sources of the real-data runs")
    add("")
    for p in real:
        src = p.get("data_source") or "_(not recorded)_"
        add(f"- **`{p['project']}`** — {src}")
    add("")

    if synth:
        add("### The runs that are *not* on real data")
        add("")
        for p in synth:
            add(f"- **`{p['project']}`** — {p.get('data_source') or '—'}")
        add("")
        add("These are labelled synthetic in their own result files and must not")
        add("be cited as measured results.")
        add("")

    add("## Measured figures")
    add("")
    add("Only figures a project's own run reported. A metric absent here was")
    add("not measured, however often it may appear elsewhere.")
    add("")
    add("| Project | Metric | Value | Note |")
    add("|---|---|---:|---|")
    any_headline = False
    for p in rows:
        for h in p.get("headline") or []:
            any_headline = True
            add(f"| `{p['project']}` | {h['metric']} | {_fmt(h['value'])} | "
                f"{h.get('note') or ''} |")
    if not any_headline:
        add("| _(none reported)_ | | | |")
    add("")

    add("## Petition claims vs. what this portfolio can show")
    add("")
    add("The point of this table is the gap. A claim listed as *partially")
    add("addressed* or *not evidenced* must not be cited to this repository.")
    add("")
    add("| Claim | Project | Status |")
    add("|---|---|---|")
    for c in results.get("claims_status") or []:
        add(f"| {c['claim']} | `{c['project']}` | **{c['status']}** |")
    add("")
    for c in results.get("claims_status") or []:
        add(f"**{c['claim']}** — `{c['project']}`  ")
        add(f"{c['detail']}")
        add("")

    add("## What this roll-up does *not* establish")
    add("")
    add("- It does not verify any project's method. It reports what each run")
    add("  recorded, including runs whose result is poor.")
    add("- It does not establish adoption. No download count, citation or")
    add("  external user appears anywhere in this portfolio.")
    add("- Its own `is_synthetic` is `true`: the roll-up has no data source of")
    add("  its own beyond the other projects' result files.")
    add("")
    return "\n".join(out) + "\n"
