"""Builds website/ from the last demo run."""
from __future__ import annotations
import pathlib
from . import sitekit as sk

ROOT = pathlib.Path(__file__).resolve().parent.parent
META = {
    "name": "Measured Results",
    "slug": "measured-results",
    "repo": "3.0-Financial-Ai-Systems",
    "pillar": "Financial Stability",
    "tagline": "Every figure the portfolio can actually support, read from the file "
               "each project's own demo wrote — and every claim it cannot.",
    "tags": [("reads 21 projects", ""), ("no hand-entered numbers", ""),
             ("claims audit", "warn")],
    "banner": "This page is generated by walking the five repositories and reading "
              "each project's results/latest.json. A number with no run behind it "
              "cannot appear here, and a project that has never been run is listed as "
              "such rather than omitted. All current runs use synthetic or authored "
              "data.",
}

_STATUS_CLASS = {"not evidenced": "c3", "contradicted by the run": "c4",
                 "partially addressed": "c2", "evidenced": "c1"}


def build_site(results: dict) -> pathlib.Path:
    s = results["summary"]
    projects = results["projects"]

    metrics = sk.metric_grid([
        ("Projects", s["n_projects"], f"across {len(s['repos'])} repositories"),
        ("With a recorded run", s["n_with_results"], f"{s['n_never_run']} never run"),
        ("On real data", s["n_real_data"], f"{s['n_synthetic_data']} on synthetic"),
        ("Tests", s["total_tests"], "across the portfolio"),
    ])

    proj_rows = []
    for p in projects:
        heads = "; ".join(f"{h['metric']} {h['value']}" for h in p["headline"][:2])
        proj_rows.append([p["repo"].split("-")[0], p["project"],
                          "yes" if p["has_results"] else "no",
                          p["n_tests"], "yes" if p["has_site"] else "no",
                          heads or "—"])
    proj_tbl = sk.table(
        ["Repo", "Project", "Run", "Tests", "Site", "Headline measured figures"],
        proj_rows, numeric_cols=(3,))

    claim_rows = [[c["claim"], c["project"], c["status"], c["detail"]]
                  for c in results["claims_status"]]
    claim_tbl = sk.table(
        ["Claim", "Project that would evidence it", "Status", "What the run shows"],
        claim_rows)

    detail_blocks = []
    for p in projects:
        if not p["headline"]:
            continue
        rows = [[h["metric"], h["value"], h["note"] or "—"] for h in p["headline"]]
        detail_blocks.append(
            f"<h3>{sk.esc(p['project'])}</h3>"
            + sk.table(["Metric", "Value", "Note"], rows, numeric_cols=(1,)))

    test_chart = sk.bar_chart(
        [(p["project"][:26], p["n_tests"]) for p in projects if p["n_tests"]],
        fmt="{:.0f}")

    body = f"""
<section>
  <h2>Why this page exists</h2>
  <div class="stack">
    <p>Numbers get quoted in a CV, a README or a petition, and over time nobody can say
    which run produced them or whether that run still exists. Every figure below is read
    from the JSON file the project's own demo wrote. A number with no run behind it
    cannot appear here, and a project that has never been run is listed as such rather
    than quietly left out.</p>
    <p>That constraint is the product. It is also why the "on real data" count reads
    <strong>{s['n_real_data']}</strong>.</p>
  </div>
</section>

<section>
  <h2>Portfolio state</h2>
  <div class="stack-lg">
    {metrics}
    <p class="mono" style="color:var(--muted);font-size:12.5px">
      generated {sk.esc(results['generated_at'])} &middot; read from
      {s['n_with_results']} results files
    </p>
    {proj_tbl}
  </div>
</section>

<section>
  <h2>Petition claims against what the code shows</h2>
  <div class="stack-lg">
    {claim_tbl}
    <div class="note warn" style="background:var(--warn-bg);border-color:transparent">
      <h3>Read the status column literally</h3>
      <p>"Not evidenced" means the repository cannot support the claim today — not that
      the claim is false. Several are supported by work recorded elsewhere in the
      résumé. What this table establishes is narrower and more useful: which claims a
      reader following the code would be unable to verify.</p>
      <p>One row says <em>contradicted by the run</em>. The audit agent's measured
      review-load change is 0.0% and it currently loses to the rule-based baseline. That
      is on the page because a roll-up that only reported the flattering projects would
      defeat its own purpose.</p>
    </div>
  </div>
</section>

<section>
  <h2>Test coverage by project</h2>
  <div class="stack-lg">
    {test_chart}
    <p>{s['total_tests']} tests across {s['n_projects']} projects. These guard
    behaviour, not imports: several encode findings directly, so that a regression
    changes a test result rather than silently changing a number on a website.</p>
  </div>
</section>

<section>
  <h2>Every measured figure</h2>
  <div class="stack-lg">
    {"".join(detail_blocks)}
  </div>
</section>

<section>
  <h2>Reproduce it</h2>
  <div class="stack">
    <pre># run every project first, then roll up
for d in ../../*/*/; do (cd "$d" && python -m src.demo); done
cd measured-results && python -m src.demo</pre>
  </div>
</section>

<section>
  <h2>What this does not establish</h2>
  <div class="stack">
    <ul class="tight">
      <li>Every run behind these numbers used synthetic or authored data. The
      portfolio currently contains <strong>{s['n_real_data']}</strong> projects with
      a result computed on real data.</li>
      <li>Several projects were validated against corpora written by the same person
      who wrote the method. Those figures measure internal consistency, and each
      project's own page says so.</li>
      <li>{s['n_never_run']} projects have no recorded run at all.</li>
      <li>This page checks that figures trace to a run. It cannot check that the
      run was well designed — that judgement stays with each project's page.</li>
    </ul>
  </div>
</section>
"""
    return sk.build(ROOT, META, body, results)
